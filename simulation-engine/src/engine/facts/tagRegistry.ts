export const DYNAMIC_TAG_PATTERNS: readonly RegExp[] = [
  /^#AwakenedChaosDragon_[A-Za-z0-9_-]*$/,
  /^#DragonLeys_[A-Za-z0-9_-]*$/,
  /^#(Grudge|PrevailedOver|Resisted|ThwartedBy):[A-Za-z0-9_-]*$/,
  /^#Warped_[A-Za-z0-9_-]*$/,
  /^#(Want|Flaw|Line)_[A-Za-z0-9_-]+$/,
];

const DERIVED_SET = new Set<string>(DERIVED_TAGS);
const HISTORY_SET = new Set<string>(HISTORY_TAGS);
const MOTIVE_SET = new Set<string>(MOTIVE_TAGS);
const REACTION_SET = new Set<string>(REACTION_TAGS);

export const ALL_REGISTERED_TAGS: ReadonlySet<string> = new Set<string>([
  ...DERIVED_TAGS,
  ...HISTORY_TAGS,
  ...MOTIVE_TAGS,
  ...REACTION_TAGS,
]);

export function getTagGroup(tag: string): TagGroup | null {
  if (DERIVED_SET.has(tag)) return "derived";
  if (HISTORY_SET.has(tag)) return "history";
  if (MOTIVE_SET.has(tag)) return "motive";
  if (REACTION_SET.has(tag)) return "reaction";
  if (DYNAMIC_TAG_PATTERNS.some((re) => re.test(tag))) {
    return /^#(Want|Flaw|Line)_/.test(tag) ? "motive" : "history";
  }
  return null;
}

export function isRegisteredTag(tag: string): boolean {
  return ALL_REGISTERED_TAGS.has(tag) || DYNAMIC_TAG_PATTERNS.some((re) => re.test(tag));
}
